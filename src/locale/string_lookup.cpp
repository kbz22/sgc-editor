const std::optional<std::wstring> locale::StringLookup::Get(StringId id) const
{
    auto it = m_strings.find(id);

    std::optional<std::wstring> result = std::nullopt;

    if (it != m_strings.end())
    {
        result = std::optional<std::wstring>{it->second};
    }

    return result;
}
